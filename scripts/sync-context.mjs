#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const dataDir = path.join(projectRoot, 'data');
const appContextPath = path.join(projectRoot, 'APP_CONTEXT.md');
const manifestPath = path.join(dataDir, 'portal-manifest.json');

console.log('⚡ [Self-Annealing Context Engine] Starting context scan and verification...');

if (!fs.existsSync(dataDir)) {
  console.error(`❌ Data directory missing at ${dataDir}`);
  process.exit(1);
}

const subjects = fs
  .readdirSync(dataDir)
  .filter((f) => fs.statSync(path.join(dataDir, f)).isDirectory());

let totalFiles = 0;
let totalQuestions = 0;
let brandViolations = 0;
const violationsList = [];

const gradeStats = {
  '9': { modules: 0, questions: 0, subjects: new Set() },
  '10': { modules: 0, questions: 0, subjects: new Set() },
  '11': { modules: 0, questions: 0, subjects: new Set() },
  '12': { modules: 0, questions: 0, subjects: new Set() },
};

const subjectStats = {};

for (const sub of subjects) {
  const dir = path.join(dataDir, sub);
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json') && f !== 'chapters-index.json');

  // Determine grade from directory name (e.g., 'chemistry-12' -> '12')
  const gradeMatch = sub.match(/-(\d+)$/);
  const grade = gradeMatch ? gradeMatch[1] : 'other';
  const baseSubject = sub.replace(/-\d+$/, '');

  if (!subjectStats[baseSubject]) {
    subjectStats[baseSubject] = { modules: 0, questions: 0, grades: [] };
  }
  if (!subjectStats[baseSubject].grades.includes(grade)) {
    subjectStats[baseSubject].grades.push(grade);
  }

  for (const f of files) {
    totalFiles++;
    const filePath = path.join(dir, f);
    const contentRaw = fs.readFileSync(filePath, 'utf8');

    // 1. Brand Neutrality Check (zero tolerance for 'sochbadlo')
    if (/sochbadlo/i.test(contentRaw)) {
      brandViolations++;
      violationsList.push(filePath);
    }

    try {
      const parsed = JSON.parse(contentRaw);
      const qCount = Array.isArray(parsed.questions) ? parsed.questions.length : 0;
      totalQuestions += qCount;

      if (gradeStats[grade]) {
        gradeStats[grade].modules++;
        gradeStats[grade].questions += qCount;
        gradeStats[grade].subjects.add(baseSubject);
      }

      subjectStats[baseSubject].modules++;
      subjectStats[baseSubject].questions += qCount;
    } catch (err) {
      console.error(`⚠️ Failed to parse JSON in ${filePath}:`, err.message);
    }
  }
}

// Convert Set to count for JSON serialization
const gradeSummary = {};
for (const [g, data] of Object.entries(gradeStats)) {
  gradeSummary[`Class ${g}`] = {
    modules: data.modules,
    questions: data.questions,
    subjectCount: data.subjects.size,
  };
}

const nowIso = new Date().toISOString();

// Machine-readable manifest
const manifest = {
  name: 'FBISE Prep Portal Manifest',
  version: '2.0.0',
  lastAnnealedAt: nowIso,
  integrity: {
    totalSubjects: subjects.length,
    totalModuleFiles: totalFiles,
    totalQuestions: totalQuestions,
    totalStaticRoutes: totalFiles + 5, // Includes root, 404, etc.
    brandViolations: brandViolations,
  },
  grades: gradeSummary,
  subjects: subjectStats,
};

// 1. Write data/portal-manifest.json
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf8');
console.log(`✅ [Self-Annealing Context Engine] Manifest generated at data/portal-manifest.json`);

// 2. Self-anneal APP_CONTEXT.md
if (fs.existsSync(appContextPath)) {
  let appContextContent = fs.readFileSync(appContextPath, 'utf8');

  const metricsSection = `<!-- AUTOGENERATED_METRICS_START -->
### Live Verified System State
- **Last Self-Annealed**: \`${nowIso}\`
- **Total Subject Tracks**: \`${subjects.length}\` active disciplines
- **Total Static Module Files**: \`${totalFiles}\` verified JSON datasets
- **Total Board Questions (MCQs)**: \`${totalQuestions.toLocaleString()}\` authenticated exam questions
- **Brand Neutrality Compliance**: \`${brandViolations === 0 ? '100% CLEAN (0 Violations)' : `${brandViolations} VIOLATIONS DETECTED`}\`
- **Grade Coverage**:
  - **Class 9 (SSC-I)**: \`${gradeStats['9'].modules}\` modules · \`${gradeStats['9'].questions.toLocaleString()}\` MCQs
  - **Class 10 (SSC-II)**: \`${gradeStats['10'].modules}\` modules · \`${gradeStats['10'].questions.toLocaleString()}\` MCQs
  - **Class 11 (HSSC-I)**: \`${gradeStats['11'].modules}\` modules · \`${gradeStats['11'].questions.toLocaleString()}\` MCQs
  - **Class 12 (HSSC-II)**: \`${gradeStats['12'].modules}\` modules · \`${gradeStats['12'].questions.toLocaleString()}\` MCQs
<!-- AUTOGENERATED_METRICS_END -->`;

  if (appContextContent.includes('<!-- AUTOGENERATED_METRICS_START -->')) {
    appContextContent = appContextContent.replace(
      /<!-- AUTOGENERATED_METRICS_START -->[\s\S]*?<!-- AUTOGENERATED_METRICS_END -->/,
      metricsSection
    );
  } else {
    // Append to Section 6 of APP_CONTEXT.md
    appContextContent += `\n\n## 8. Live Self-Annealed Verification\n\n${metricsSection}\n`;
  }

  fs.writeFileSync(appContextPath, appContextContent, 'utf8');
  console.log(`✅ [Self-Annealing Context Engine] APP_CONTEXT.md self-annealed with live metrics.`);
}

console.log('─────────────────────────────────────────────────────────────────');
console.log(`📊 Total Modules:   ${totalFiles}`);
console.log(`📚 Total MCQs:      ${totalQuestions.toLocaleString()}`);
console.log(`🛡️  Brand Check:     ${brandViolations === 0 ? '0 Violations (Clean)' : `${brandViolations} Violations!`}`);
console.log('─────────────────────────────────────────────────────────────────');

if (brandViolations > 0) {
  console.error('❌ Brand violations found in:', violationsList);
  process.exit(1);
}

console.log('✨ [Self-Annealing Context Engine] System context is healthy, validated, and up-to-date.');
